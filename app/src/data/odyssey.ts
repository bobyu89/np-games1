/** 一段試煉：一種劫影，對到史詩裡的一段，和那個主訴最容易掉進去的推理陷阱 */
export interface Peril {
  complaint: string;
  /** 「獨眼巨人之劫」 */
  name: string;
  /** 史詩裡發生了什麼，兩三句 */
  myth: string;
  /** 對到臨床的哪一個陷阱 */
  trap: string;
  /** 沒掉進去的時候說的話 */
  pass: string;
  /** 掉進去了，下一次怎麼過 */
  next: string;
  /** 這個陷阱叫什麼。kind 是 bias：認知偏誤（照 Croskerry, 2003 的名稱）；habit：不是偏誤，是常漏掉的一個習慣 */
  bias: { name: string; en: string; kind: 'bias' | 'habit'; what: string };
}

